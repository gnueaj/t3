def bend(key, a, b, w=2.4, vertical=False):
    """두 조각을 잇는 보라 실: 곧은 선 대신 양 끝에서 수평(vertical이면 수직)으로 나가 부드럽게 굽는 실."""
    (ax, ay), (bx_, by_) = a, b
    if vertical:
        d = (by_ - ay) * 0.5
        pts = [a, (ax, ay + d), (bx_, by_ - d), b]
    else:
        d = (bx_ - ax) * 0.5
        pts = [a, (ax + d, ay), (bx_ - d, by_), b]
    return C(key, pts, color=PURPLE2, w=w)


