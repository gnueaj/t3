def vis_chips(chips, note):
    def draw(x, y, w, h):
        cw, ch, g = (w - 36 - 10) / 2, 30, 10
        top = y + (h - (2 * ch + g + 28)) / 2
        out = []
        for i, c in enumerate(chips):
            cx, cy = x + 18 + (i % 2) * (cw + 10), top + (i // 2) * (ch + g)
            out += [R('vc/%d' % i, cx, cy, cw, ch, prst='roundRect', radius=10, fill='FFFFFF', line='D9CFFF', line_w=1.0),
                    T('vc/%dt' % i, cx, cy, cw, ch, c, size=10.5, color=INK, weight='m', align='c', anchor='ctr')]
        out.append(T('vc/n', x + 18, top + 2 * ch + g + 8, w - 36, 20, note, size=10.5, color=PURPLE, weight='b', align='c', anchor='ctr'))
        return out
    return draw


