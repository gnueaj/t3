def ux_page(key, code, title, steps, data, bar, notes, foot, gap=14, weights=None, pins=()):
    s = page_slide(key, code, [(title, INK)])
    legend(s, 96)
    y = 120 + pipeline(s, 'qc/f', 120, None, steps, gap=gap, name_pt=12.5, desc_pt=10.5, weights=weights)
    y += data_row(s, 'qc/d', y, data, gap=gap, weights=weights) + 12
    y += timebar(s, 'qc/tb', X, y, W, *bar, pins=pins) + 6
    s.add('qc/tbn', [T('qc/tbn', X, y, W, 18, '기준 속도: ' + NUM.BASIS + ' (B-2)', size=10, color=SUB, anchor='ctr')])
    y += 18 + 16
    y += notes3(s, 'qc/n', y, notes) + 12
    footnote(s, foot, y)
    return s


