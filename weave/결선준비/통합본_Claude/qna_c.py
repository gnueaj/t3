RRF_K = 60


def rrf_strip(s, key, y, h=58):
    """03 단계에서 두 검색의 순위를 합치는 식(RRF)과 셈한 예. 13차: 'RRF 공식 써 주면 좋을 듯'. 돌려줌: 높이."""
    a, b = 1 / (RRF_K + 2) + 1 / (RRF_K + 5), 1 / (RRF_K + 1)
    lh = lh_of(12, 1.5)
    lw = 640                                        # 왼쪽(식)의 폭. 오른쪽은 셈한 예
    s.add(key, [R(key + '/bg', X, y, W, h, prst='roundRect', radius=12, fill=GRAY_BG, line=None),
                T(key + '/f', X + 20, y + (h - 2 * lh) / 2, lw - 30, 2 * lh + 4,
                  [[('순위를 합치는 식 (RRF)¹   ', dict(color=PURPLE, weight='b')), ('RRF(d) = ∑ᵣ 1 / (k + rankᵣ(d)),   k = %d' % RRF_K, dict(color=INK, weight='b'))],
                   [('Weave의 03 단계   ', dict(color=SUB)), ('1 / (%d + 임베딩 검색의 순위)  +  1 / (%d + BM25의 순위)' % (RRF_K, RRF_K), dict(color=INK))]],
                  size=12, lnspc=lh * 0.75),
                R(key + '/ln', X + lw, y + 10, 1, h - 20, fill='DCD5EE', line=None),
                T(key + '/e', X + lw + 20, y + (h - 2 * lh) / 2, W - lw - 36, 2 * lh + 4,
                  [[('예   ', dict(color=PURPLE, weight='b')), ('임베딩 2위, BM25 5위인 기록 = 1/%d + 1/%d = %.4f' % (RRF_K + 2, RRF_K + 5, a), dict(color=INK))],
                   [('한쪽에서만 1위인 기록(1/%d = %.4f)보다 앞에 놓임' % (RRF_K + 1, b), dict(color=BODY))]],
                  size=11.5, lnspc=lh * 0.75)])
    return h


